import { defineConfig } from "@playwright/test";

// Съёмка ролика, а не проверка. Отсюда и настройки: один рабочий поток,
// без повторов, с записью следа — из него recast и собирает видео.
export default defineConfig({
  testDir: ".",
  workers: 1,
  retries: 0,
  // Ролик идёт около минуты, и это не признак зависания: стандартные
  // тридцать секунд рассчитаны на проверку, а здесь съёмка с паузами
  // на прочтение подписей.
  timeout: 180_000,
  use: {
    baseURL: "http://localhost:5177",
    // ⚠️ ОКНО 1280, А СНИМОК 2560 — В ЭТОМ ВСЯ РЕЗКОСТЬ. Страница верстается
    // как на обычном экране, но рисуется с двойной плотностью, и снимок
    // выходит вдвое детальнее вёрстки. Вырезая из него кусок, мы приближаем,
    // не растягивая: буквы остаются буквами.
    //
    // С записью экрана этот приём не работает — там двойная плотность кладёт
    // страницу в угол холста, проверено. Ещё одна причина снимать кадрами:
    // запись идёт в VP8 с низким потоком и текст в ней плывёт при любом
    // разрешении. Это и было причиной мутного первого ролика.
    viewport: { width: 1280, height: 720 },
    deviceScaleFactor: 2,
    // Ни следа, ни видео: ролик собирается из снимков, а не из записи.
    trace: "off",
    video: "off",
  },
  // Пример поднимается сам. Если он уже запущен — берём запущенный.
  webServer: {
    command: "npm run example -- --port 5177 --strictPort",
    cwd: "..",
    url: "http://localhost:5177",
    reuseExistingServer: true,
    timeout: 120_000,
  },
});
